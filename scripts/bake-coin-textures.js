// Bakes the coin face PNGs into small RGB pixel buffers so the 3D coin never
// depends on loading image assets at runtime (one face used to come up blank).
const fs = require('fs')
const path = require('path')
const { PNG } = require('pngjs')

const SIZE = 256
const BG = [74, 38, 24]

function bake(file) {
  const src = PNG.sync.read(fs.readFileSync(path.join(__dirname, '..', 'assets', 'images', file)))
  const out = Buffer.alloc(SIZE * SIZE * 3)
  const scale = src.width / SIZE
  for (let y = 0; y < SIZE; y += 1) {
    for (let x = 0; x < SIZE; x += 1) {
      const sx0 = Math.floor(x * scale)
      const sy0 = Math.floor(y * (src.height / SIZE))
      const sx1 = Math.max(sx0 + 1, Math.floor((x + 1) * scale))
      const sy1 = Math.max(sy0 + 1, Math.floor((y + 1) * (src.height / SIZE)))
      let r = 0, g = 0, b = 0, n = 0
      for (let yy = sy0; yy < sy1; yy += 1) {
        for (let xx = sx0; xx < sx1; xx += 1) {
          const i = (yy * src.width + xx) * 4
          const a = src.data[i + 3] / 255
          r += src.data[i] * a + BG[0] * (1 - a)
          g += src.data[i + 1] * a + BG[1] * (1 - a)
          b += src.data[i + 2] * a + BG[2] * (1 - a)
          n += 1
        }
      }
      const o = (y * SIZE + x) * 3
      out[o] = r / n
      out[o + 1] = g / n
      out[o + 2] = b / n
    }
  }
  return out.toString('base64')
}

const body = `// Generated by scripts/bake-coin-textures.js — do not edit.
export const COIN_TEXTURE_SIZE = ${SIZE}
export const COIN_HEADS_RGB = '${bake('coin.png')}'
export const COIN_TAILS_RGB = '${bake('coin-tail.png')}'
`
fs.writeFileSync(path.join(__dirname, '..', 'src', 'constants', 'coinTextures.ts'), body)
console.log('written', body.length, 'bytes')
